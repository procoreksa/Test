def caption(post, network):
    pid, fmt, title, files, text, cta, tag, contact = post
    out = text
    if contact:
        out += "\n\n" + (CONTACT_FB if network == "facebook" else CONTACT_IG)
    if network == "instagram":
        out += "\n\n" + TAGS[tag] + " #ProCoreLaunch"
    return out


def schedule():
    for i, p in enumerate(POSTS):
        d = START + timedelta(days=i // 4)
        yield p, d.isoformat(), SLOTS[i % 4]


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    with open(os.path.join(here, "calendar.csv"), "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["campaign", "content_id", "day", "date", "time_riyadh", "platforms", "format", "title", "files", "cta", "caption_ig", "status"])
        for i, (p, d, t) in enumerate(schedule()):
            w.writerow([LABEL, p[0], i // 4 + 1, d, t, "IG+FB", p[1], p[2], " | ".join(p[3]), p[5], caption(p, "instagram"), "planned"])
    with open(os.path.join(here, "calendar.md"), "w") as f:
        f.write(f"# {LABEL} — تقويم النشر (28 منشور)\n\nالمنطقة الزمنية: Asia/Riyadh · المنصات: Instagram + Facebook (منشور منفصل لكل منصة)\n\n")
        f.write("| ID | اليوم | التاريخ | الوقت | الصيغة | العنوان | الملفات |\n|---|---|---|---|---|---|---|\n")
        for i, (p, d, t) in enumerate(schedule()):
            f.write(f"| {p[0]} | {i // 4 + 1} | {d} | {t} | {p[1]} | {p[2]} | {len([x for x in p[3] if not x.endswith('cover.jpg')])} |\n")
        f.write("\n## النصوص\n")
        for p, d, t in schedule():
            f.write(f"\n### {p[0]} — {p[2]} ({d} {t})\n\n```\n{caption(p, 'instagram')}\n```\n")
    print("ok", len(POSTS))


if __name__ == "__main__":
    main()
